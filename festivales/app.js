/* =========================================================
   BUSCAR IMAGEN EN WIKIMEDIA COMMONS
   ========================================================= */

async function buscarImagenFestival(
    festival
) {

    const clave =
        festival.nombre;


    if (
        Object.prototype.hasOwnProperty.call(
            imagenesFestivales,
            clave
        )
    ) {

        return imagenesFestivales[
            clave
        ];

    }


    const consulta =
        `${festival.nombre} ${festival.localidad} Japan`;


    const url =
        "https://commons.wikimedia.org/w/api.php?" +
        new URLSearchParams({

            action: "query",

            generator: "search",

            gsrsearch: consulta,

            gsrnamespace: "6",

            gsrlimit: "8",

            prop: "imageinfo",

            iiprop: "url|extmetadata",

            iiurlwidth: "640",

            format: "json",

            origin: "*"

        });


    try {

        const respuesta =
            await fetch(url);


        const datos =
            await respuesta.json();


        if (
            !datos.query ||
            !datos.query.pages
        ) {

            imagenesFestivales[
                clave
            ] = null;

            return null;

        }


        const paginas =
            Object.values(
                datos.query.pages
            );


        const imagenes =
            paginas.filter(
                pagina => {

                    if (
                        !pagina.imageinfo ||
                        !pagina.imageinfo[0]
                    ) {

                        return false;

                    }


                    const info =
                        pagina.imageinfo[0];


                    if (!info.thumburl) {

                        return false;

                    }


                    const titulo =
                        pagina.title
                            .toLowerCase();


                    if (
                        titulo.includes("map") ||
                        titulo.includes("logo") ||
                        titulo.includes("flag") ||
                        titulo.includes("icon")
                    ) {

                        return false;

                    }


                    return true;

                }
            );


        if (
            imagenes.length === 0
        ) {

            imagenesFestivales[
                clave
            ] = null;

            return null;

        }


        const pagina =
            imagenes[0];


        const info =
            pagina.imageinfo[0];


        const resultado = {

            imagen:
                info.thumburl ||
                info.url,

            pagina:
                "https://commons.wikimedia.org/wiki/" +
                encodeURIComponent(
                    pagina.title.replace(
                        / /g,
                        "_"
                    )
                ),

            titulo:
                pagina.title.replace(
                    "File:",
                    ""
                )

        };


        imagenesFestivales[
            clave
        ] = resultado;


        return resultado;

    }
    catch (error) {

        console.error(
            "No se pudo obtener la imagen:",
            festival.nombre,
            error
        );


        imagenesFestivales[
            clave
        ] = null;


        return null;

    }

}


/* =========================================================
   CONTENEDOR DE IMAGEN
   ========================================================= */

function crearContenedorImagen(
    festival
) {

    const id =
        "imagen-" +
        festival.nombre
            .normalize("NFD")
            .replace(
                /[\u0300-\u036f]/g,
                ""
            )
            .replace(
                /[^a-zA-Z0-9]/g,
                "-"
            );


    return `

        <div
            class="festival-imagen"
            id="${id}"
        >

            <div class="imagen-cargando">

                📷 Buscando fotografía...

            </div>

        </div>

    `;

}


/* =========================================================
   CARGAR IMAGEN
   ========================================================= */

async function cargarImagenFestival(
    festival,
    contenedor
) {
    if (!contenedor) {

        return;

    }


    const resultado =
        await buscarImagenFestival(
            festival
        );


    if (!resultado) {

        contenedor.innerHTML = `

            <div class="imagen-no-disponible">

                📷 No se encontró una fotografía
                disponible.

            </div>

        `;

        return;

    }


    contenedor.innerHTML = `

        <a
            href="${resultado.pagina}"
            target="_blank"
            rel="noopener noreferrer"
        >

            <img
                src="${resultado.imagen}"
                alt="${festival.nombre}"
                loading="lazy"
                decoding="async"
            >

        </a>


        <div class="imagen-fuente">

            📷

            <a
                href="${resultado.pagina}"
                target="_blank"
                rel="noopener noreferrer"
            >

                Wikimedia Commons

            </a>

        </div>

    `;

}


const observadorImagenesFestivales =
    "IntersectionObserver" in window
        ? new IntersectionObserver(
            entradas => {
                entradas.forEach(entrada => {
                    if (!entrada.isIntersecting) {
                        return;
                    }

                    observadorImagenesFestivales.unobserve(
                        entrada.target
                    );
                    cargarImagenFestival(
                        entrada.target._festival,
                        entrada.target
                    );
                });
            },
            { rootMargin: "250px 0px" }
        )
        : null;


function observarImagenFestival(festival, contenedor) {
    if (!contenedor) {
        return;
    }

    contenedor._festival = festival;
    if (observadorImagenesFestivales) {
        observadorImagenesFestivales.observe(contenedor);
    } else {
        cargarImagenFestival(festival, contenedor);
    }
}


/* =========================================================
   BOTÓN MAPA
   ========================================================= */

function crearBotonMapa(
    festival
) {

    const coordenadas =
        coordenadasFestivales[
            festival.localidad
        ];


    if (!coordenadas) {

        return "";

    }


    const parametros =
        new URLSearchParams({

            nombre:
                festival.nombre,

            localidad:
                festival.localidad,

            prefectura:
                festival.prefectura,

            lat:
                coordenadas.lat,

            lng:
                coordenadas.lng

        });


    return `

        <a
            class="boton-mapa"
            href="../mapa/index.html?${parametros.toString()}"
        >

            📍 Abrir en mapa

        </a>

    `;

}



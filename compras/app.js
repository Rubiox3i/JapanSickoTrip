function esFavorito(id) {

    return favoritos.includes(id);

}


function estaComprado(id) {

    return comprados.includes(id);

}


function alternarFavorito(id) {

    if (esFavorito(id)) {

        favoritos =
            favoritos.filter(
                item => item !== id
            );

    } else {

        favoritos.push(id);

    }

    guardarEstado();

    renderizar();

}


function alternarComprado(id) {

    if (estaComprado(id)) {

        comprados =
            comprados.filter(
                item => item !== id
            );

    } else {

        comprados.push(id);

    }

    guardarEstado();

    renderizar();

}



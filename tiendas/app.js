const STORAGE_KEY =
    "japanSickoTiendasFavoritas";


let favoritos = JSON.parse(
    localStorage.getItem(STORAGE_KEY) || "[]"
);


let filtroActual = "todas";


const contenido =
    document.getElementById(
        "contenido-tiendas"
    );


const contador =
    document.getElementById(
        "contador"
    );


/* =========================================================
   FAVORITOS
   ========================================================= */

function guardarFavoritos() {

    localStorage.setItem(
        STORAGE_KEY,
        JSON.stringify(favoritos)
    );

}


function esFavorita(nombre) {

    return favoritos.includes(nombre);

}


function alternarFavorito(nombre) {

    if (esFavorita(nombre)) {

        favoritos =
            favoritos.filter(
                item => item !== nombre
            );

    } else {

        favoritos.push(nombre);

    }

    guardarFavoritos();

    renderizar();

}


/* =========================================================
   ESTRELLAS DE PRECIO
   ========================================================= */

function obtenerPrecioEstrellas(precio) {

    return "⭐".repeat(precio);

}


/* =========================================================
   FILTRADO
   ========================================================= */

function obtenerTiendas() {

    let resultado = [...tiendas];


    if (filtroActual === "todas") {

        return resultado;

    }


    if (filtroActual === "favoritos") {

        return resultado.filter(
            tienda =>
                esFavorita(tienda.nombre)
        );

    }


    if (filtroActual === "baratas") {

        return resultado
            .filter(
                tienda =>
                    tienda.precio >= 4
            )
            .sort(
                (a, b) =>
                    b.precio - a.precio
            );

    }


    if (filtroActual === "imprescindibles") {

        return resultado.filter(
            tienda =>
                tienda.importancia ===
                "imprescindible"
        );

    }


    return resultado.filter(
        tienda =>
            tienda.categorias.includes(
                filtroActual
            )
    );

}



/* =========================================================
   DIBUJAR CALENDARIO
   ========================================================= */

function dibujarCalendario() {

    calendario.innerHTML = "";


    mesTitulo.textContent =
        meses[
            mesActual
        ];


    const primerDia =
        new Date(
            2026,
            mesActual,
            1
        );


    let diaSemana =
        primerDia.getDay();


    diaSemana =
        diaSemana === 0
            ? 6
            : diaSemana - 1;


    const diasMes =
        new Date(
            2026,
            mesActual + 1,
            0
        ).getDate();


    for (
        let i = 0;
        i < diaSemana;
        i++
    ) {

        const vacio =
            document.createElement(
                "div"
            );


        vacio.className =
            "dia vacio";


        calendario.appendChild(
            vacio
        );

    }


    for (
        let dia = 1;
        dia <= diasMes;
        dia++
    ) {

        const elemento =
            document.createElement(
                "div"
            );


        elemento.className =
            "dia";


        const numero =
            document.createElement(
                "div"
            );


        numero.className =
            "numero-dia";


        numero.textContent =
            dia;


        elemento.appendChild(
            numero
        );


        const eventos =
            festivales.filter(
                festival =>
                    festival.mes === mesActual &&
                    festival.calendario === true &&
                    festival.diaCalendario === dia
            );


        if (
            eventos.length > 0
        ) {

            elemento.classList.add(
                "con-festival"
            );


            eventos.forEach(
                festival => {

                    const marca =
                        document.createElement(
                            "span"
                        );


                    marca.className =
                        "marca-festival";


                    marca.innerHTML = `

                        <span class="punto-festival"></span>

                        ${festival.nombre}

                    `;


                    elemento.appendChild(
                        marca
                    );

                }
            );


            elemento.addEventListener(
                "click",
                () => {

                    mostrarDia(
                        mesActual,
                        dia
                    );

                }
            );

        }


        calendario.appendChild(
            elemento
        );

    }

}



/* =========================================================
   RENDERIZADO
   ========================================================= */

function renderizar() {

    const visibles =
        obtenerTiendas();


    contador.textContent =
        visibles.length === 1
            ? "1 tienda"
            : `${visibles.length} tiendas`;


    if (
        visibles.length === 0
    ) {

        contenido.innerHTML = `

            <div class="sin-resultados">

                <div>
                    ❤️
                </div>

                <h3>
                    Aún no tienes tiendas marcadas
                </h3>

                <p>
                    Pulsa «Quiero ir» en las tiendas que quieras visitar.
                </p>

            </div>

        `;


        conectarFavoritos();

        return;

    }


    contenido.innerHTML = "";


    const seccion =
        document.createElement(
            "section"
        );


    seccion.className =
        "categoria-seccion";


    const titulo =
        filtros[filtroActual]
            ? filtros[filtroActual].titulo
            : "🏪 Tiendas";


    seccion.innerHTML = `

        <div class="categoria-titulo">

            <h2>
                ${titulo}
            </h2>

            <span>
                ${visibles.length}
                ${
                    visibles.length === 1
                        ? "tienda"
                        : "tiendas"
                }
            </span>

        </div>


        <div class="tiendas-grid">

            ${visibles
                .map(
                    (tienda, index) =>
                        crearTarjeta(
                            tienda,
                            index + 1
                        )
                )
                .join("")
            }

        </div>

    `;


    contenido.appendChild(
        seccion
    );


    conectarFavoritos();

}


/* =========================================================
   CONECTAR FAVORITOS
   ========================================================= */

function conectarFavoritos() {

    document
        .querySelectorAll(
            "[data-favorito]"
        )
        .forEach(
            boton => {

                boton.addEventListener(
                    "click",
                    () => {

                        alternarFavorito(
                            boton.dataset.favorito
                        );

                    }
                );

            }
        );

}


/* =========================================================
   CONECTAR FILTROS
   ========================================================= */

document
    .querySelectorAll(
        "[data-filtro]"
    )
    .forEach(
        boton => {

            boton.addEventListener(
                "click",
                () => {


                    document
                        .querySelectorAll(
                            "[data-filtro]"
                        )
                        .forEach(
                            item =>
                                item.classList
                                    .remove(
                                        "activo"
                                    )
                        );


                    boton.classList.add(
                        "activo"
                    );


                    filtroActual =
                        boton.dataset.filtro;


                    renderizar();

                }
            );

        }
    );


/* =========================================================
   INICIO
   ========================================================= */

renderizar();
